create or replace function public.admin_list_users()
returns table(email text, credits integer, is_admin boolean, is_restricted boolean, joined_at timestamptz)
language plpgsql
security definer
set search_path to 'public'
as $$
begin
	perform require_admin();
	return query
	select p.email,
		coalesce((select sum(delta) from credit_ledger l where l.user_id = p.id), 0)::integer,
		p.is_admin, p.is_restricted, p.created_at
	from profiles p
	order by p.created_at desc;
end;
$$;

create or replace function public.admin_list_staff_flags()
returns table(email text, is_staff boolean)
language plpgsql
security definer
set search_path to 'public'
as $$
begin
	perform public.assert_admin();
	return query select profiles.email, profiles.is_staff from public.profiles;
end;
$$;

create or replace function public.admin_set_restriction(target_email text, restricted boolean)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
begin
	perform require_admin();
	update profiles set is_restricted = restricted where email = target_email;
	if not found then
		raise exception 'unknown_user';
	end if;
end;
$$;

create or replace function public.admin_set_staff(target_email text, staff boolean)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
begin
	perform public.assert_admin();
	update public.profiles set is_staff = staff where email = target_email;
end;
$$;


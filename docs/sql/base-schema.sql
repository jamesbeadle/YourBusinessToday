create or replace function public.credit_balance()
returns integer
language sql
security definer
set search_path to 'public'
as $$
	select coalesce(sum(delta), 0)::integer from credit_ledger where user_id = auth.uid();
$$;

create or replace function public.complete_stripe_purchase(
	user_identifier uuid,
	pack_identifier text,
	checkout_session_identifier text
)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
declare
	pack credit_packs%rowtype;
begin
	perform pg_advisory_xact_lock(hashtext(checkout_session_identifier));
	if exists (select 1 from purchases where stripe_checkout_session_id = checkout_session_identifier) then
		return;
	end if;
	select * into pack from credit_packs where id = pack_identifier;
	if not found then
		raise exception 'unknown_pack';
	end if;
	insert into purchases (user_id, pack_id, credits, amount_pence, stripe_checkout_session_id, status)
	values (user_identifier, pack.id, pack.credits, pack.price_pence, checkout_session_identifier, 'paid');
	insert into credit_ledger (user_id, delta, reason)
	values (user_identifier, pack.credits, 'purchase:' || pack.id);
end;
$$;

revoke execute on function public.complete_stripe_purchase(uuid, text, text) from public, anon, authenticated;
grant execute on function public.complete_stripe_purchase(uuid, text, text) to service_role;

create or replace function public.admin_grant_credits(target_email text, credit_amount integer, note text)
returns integer
language plpgsql
security definer
set search_path to 'public'
as $$
declare
	target_user_id uuid;
begin
	perform require_admin();
	if credit_amount <= 0 or credit_amount > 100000 then
		raise exception 'invalid_amount';
	end if;
	select id into target_user_id from profiles where email = target_email;
	if not found then
		raise exception 'unknown_user';
	end if;
	insert into credit_ledger (user_id, delta, reason)
	values (target_user_id, credit_amount, 'admin_grant:' || note);
	return (select sum(delta) from credit_ledger where user_id = target_user_id)::integer;
end;
$$;

create or replace function public.spend_for_agent_reply(session_identifier uuid)
returns integer
language plpgsql
security definer
set search_path to 'public'
as $$
declare
	credits_per_reply constant integer := 10;
begin
	if auth.uid() is null then
		raise exception 'not_signed_in';
	end if;
	if (select is_restricted from profiles where id = auth.uid()) then
		raise exception 'account_restricted';
	end if;
	perform pg_advisory_xact_lock(hashtext(auth.uid()::text));
	insert into agent_sessions (id, user_id) values (session_identifier, auth.uid())
	on conflict (id) do nothing;
	if credit_balance() < credits_per_reply then
		raise exception 'insufficient_credits';
	end if;
	insert into credit_ledger (user_id, delta, reason) values (auth.uid(), -credits_per_reply, 'agent_reply');
	return credit_balance();
end;
$$;


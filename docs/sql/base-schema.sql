create or replace function public.spend_for_brain_ingest(source_identifier uuid)
returns integer
language plpgsql
security definer
set search_path to 'public'
as $$
declare
	credits_per_ingest constant integer := 50;
begin
	if auth.uid() is null then
		raise exception 'not_signed_in';
	end if;
	if (select is_restricted from profiles where id = auth.uid()) then
		raise exception 'account_restricted';
	end if;
	perform pg_advisory_xact_lock(hashtext(auth.uid()::text));
	if not exists (select 1 from brain_sources where id = source_identifier and user_id = auth.uid()) then
		raise exception 'unknown_source';
	end if;
	if credit_balance() < credits_per_ingest then
		raise exception 'insufficient_credits';
	end if;
	insert into credit_ledger (user_id, delta, reason) values (auth.uid(), -credits_per_ingest, 'brain_ingest');
	return credit_balance();
end;
$$;


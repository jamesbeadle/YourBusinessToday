	<p class="font-display text-sm tracking-widest text-signal uppercase">What we build</p>
	<h1 class="font-display text-4xl leading-tight font-medium">
		AI already knows everything.<br />Except your business.
	</h1>
	<p class="text-lg text-chalk/80">
		Ask any AI assistant about the French Revolution and you will get a lecture. Ask it whether
		you can afford to hire in March, which invoices are late, or who should cover the valuation
		while Sarah is on leave, and it has nothing. Not because it is not clever, but because your
		business lives in a spreadsheet, a Word document and an inbox it has never seen.
	</p>
	<h2 class="font-display text-2xl font-medium">First, the harness</h2>
	<p class="text-chalk/80">
		So the first thing we build is a place the agent can read. We map your data sources, wherever
		the business creates a record, a document or an asset, and we build a harness that holds
		all of it: almost always a SQL database, with a table for each thing you make, a column for each
		fact about it, and every value checked at the door. Your data stops being scattered and
		becomes one thing the business, and the agent, can see.
	</p>
	<h2 class="font-display text-2xl font-medium">Then, the skills</h2>
	<p class="text-chalk/80">
		Around the harness sit the complex processes: the month-end valuation, the client report
		written from the week on site, the invoice that has to be chased. We write each one as a skill
		an LLM agent runs from start to finish, your own Claude or ChatGPT, reading the harness for its
		inputs and writing its outputs back into it. Judgement stays with the person who has it. The
		assembling, the typing and the chasing go to the agent.
	</p>
	<h2 class="font-display text-2xl font-medium">Two doors, one set of keys</h2>
	<p class="text-chalk/80">
		You reach the harness through dashboards, like any software, and through an MCP server that
		does exactly what the website does from inside the agent: the same actions, the same checks,
		no browser in the middle. One set of roles governs both. Nobody can do through Claude what they
		could not do on the screen.
	</p>
	<h2 class="font-display text-2xl font-medium">And all of it belongs to you</h2>
	<p class="text-chalk/80">
		The harness is your data in your database. The skills are written in your own language and
		they are yours. None of it is sold, pooled or used to train anything for anybody else, and it
		leaves with you if you leave us. Each stage is handed over as it goes live, and you can stop
		after any of them.
	</p>
	<p class="text-chalk/80">
		Software has spent twenty years asking businesses to adapt to it. We think the next twenty
		belong to software that adapts to the business, and that starts with giving the agent a
		business to know. Tell us about your business today, and every tomorrow gets easier.
	</p>
